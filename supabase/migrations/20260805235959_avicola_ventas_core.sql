create policy venta_detalles_select on public.venta_huevos_detalles for select to authenticated using (exists(select 1 from public.empresa_usuarios eu where eu.empresa_id=venta_huevos_detalles.empresa_id and eu.usuario_id=auth.uid() and eu.activo));
create policy venta_detalles_write on public.venta_huevos_detalles for all to authenticated using (exists(select 1 from public.ventas_huevos v join public.empresa_usuarios eu on eu.empresa_id=v.empresa_id where v.id=venta_huevos_detalles.venta_id and v.estado='BORRADOR' and eu.usuario_id=auth.uid() and eu.activo and eu.rol in ('propietario','administrador','supervisor','ventas'))) with check (exists(select 1 from public.ventas_huevos v join public.empresa_usuarios eu on eu.empresa_id=v.empresa_id where v.id=venta_huevos_detalles.venta_id and v.estado='BORRADOR' and eu.usuario_id=auth.uid() and eu.activo and eu.rol in ('propietario','administrador','supervisor','ventas')));

grant select,insert,update on public.clientes_comerciales,public.ventas_huevos,public.venta_huevos_detalles to authenticated;
