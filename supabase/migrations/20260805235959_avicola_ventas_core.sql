create policy clientes_comerciales_select on public.clientes_comerciales for select to authenticated using (exists(select 1 from public.empresa_usuarios eu where eu.empresa_id=clientes_comerciales.empresa_id and eu.usuario_id=auth.uid() and eu.activo));
create policy clientes_comerciales_write on public.clientes_comerciales for all to authenticated using (exists(select 1 from public.empresa_usuarios eu where eu.empresa_id=clientes_comerciales.empresa_id and eu.usuario_id=auth.uid() and eu.activo and eu.rol in ('propietario','administrador','supervisor','ventas'))) with check (exists(select 1 from public.empresa_usuarios eu where eu.empresa_id=clientes_comerciales.empresa_id and eu.usuario_id=auth.uid() and eu.activo and eu.rol in ('propietario','administrador','supervisor','ventas')));
create policy ventas_select on public.ventas_huevos for select to authenticated using (exists(select 1 from public.empresa_usuarios eu where eu.empresa_id=ventas_huevos.empresa_id and eu.usuario_id=auth.uid() and eu.activo));
create policy ventas_insert on public.ventas_huevos for insert to authenticated with check (exists(select 1 from public.empresa_usuarios eu where eu.empresa_id=ventas_huevos.empresa_id and eu.usuario_id=auth.uid() and eu.activo and eu.rol in ('propietario','administrador','supervisor','ventas')));
